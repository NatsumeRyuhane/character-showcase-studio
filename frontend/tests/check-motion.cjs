const fs=require('fs');
const {load,moduleScript}=require('./support/module-script.cjs');
const vm=require('vm');
const assert=require('assert/strict');
const scope={};
vm.createContext(scope);
load(scope,'src/motion-clock.js');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-9,`${a} != ${b}`);
const variants={couture:{ringSpeed:.65},orbit:{ringSpeed:1.37},still:{ringSpeed:0}};
const clock=scope.createMotionClock(0,variants);
scope.advanceMotionClock(clock,1,variants);
assert.ok(clock.rings.couture>0,'geometry moves before the showcase');
scope.advanceMotionClock(clock,3.49,variants);
const before=clock.rings.orbit;
scope.advanceMotionClock(clock,.02,variants);
near(clock.rings.orbit-before,.02*1.37);
near(clock.elapsed,4.51);
// The narrative timeline wraps, but an arbitrary geometry speed keeps its pose.
scope.advanceMotionClock(clock,11.98,variants);
const loopBoundary=clock.rings.orbit;
scope.advanceMotionClock(clock,.02,variants);
near(clock.rings.orbit-loopBoundary,.02*1.37);
near(clock.elapsed,16.51);
// Editing speed while paused does not recompute an accumulated phase.
const pose=clock.rings.couture;
variants.couture.ringSpeed=2.5;
near(clock.rings.couture,pose);
scope.advanceMotionClock(clock,.2,variants);
near(clock.rings.couture,pose+.5);
variants.couture.ringSpeed=0;
const frozen=clock.rings.couture,background=clock.elapsed;
scope.advanceMotionClock(clock,1,variants);
near(clock.rings.couture,frozen);
near(clock.elapsed,background+1);
near(clock.rings.still,0);
// Explicit seeking/replay is repeatable and respects each configured speed.
const sought=scope.createMotionClock(2,variants);
near(sought.rings.orbit,2*1.37);
const replay=scope.createMotionClock(0,variants);
near(replay.elapsed,0);
near(replay.rings.orbit,0);
console.log('PASS: intro movement, scene-boundary continuity, arbitrary-speed loop continuity, speed edits, freeze/background independence, seek and replay.');
