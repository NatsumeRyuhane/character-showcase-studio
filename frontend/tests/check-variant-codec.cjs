const fs=require('fs');
const {load,moduleScript}=require('./support/module-script.cjs');
const vm=require('vm');
const assert=require('assert/strict');
const scope=vm.createContext({});
load(scope,'src/variant-codec.js');
const encode=value=>JSON.parse(JSON.stringify(scope.encodeStudioVariants(value)));
const decode=(value,defaults)=>JSON.parse(JSON.stringify(scope.decodeStudioVariants(value,defaults)));
const copy=value=>JSON.parse(JSON.stringify(value));
const names=['couture','brutalist','cloud','plush','play','sticker','orbit','poster','wave','dual','district','tuner','arcade'];
const fixture={typeface:'editorial',cutStrength:.75,badgePalette:'soft',badgeStyle:'filled',badgeColor:'#dfe5d6',badgeInk:'#334036',badgeOpacity:.85,ringSpeed:1,ringScale:1.15,textMotion:true,textMotionStyle:'refined',textMotionAmount:.55,textMotionSpeed:1,geometryStrength:1,geometryOpacity:1,grid:true,gridMoving:true,gridOpacity:.035,gridMotion:.14,modelScale:1,parallax:true,palette:'acid',background:'light',pattern:'grid',accent:'#bceb45',effects:{gradeEnabled:true,grade:'original',gradeStrength:.7,gradeModel:false,gradient:'none',gradientStrength:.25,gradientColor:'#7b55ef',gradientMotion:true,titleGradient:false,grain:0,vignette:0,shadowEnabled:true,shadowStyle:'cut',shadowStrength:.8,shadowDepth:1,shadowColor:'#24302c'},shadows:{title:true,badges:true,model:true,geometry:false,floor:true},geometryBySeries:{atelier:'signature',fur:'signature',mini:'signature'}};
const defaults=Object.fromEntries(names.map(name=>[name,copy(fixture)]));
Object.assign(defaults.dual,{dualSplit:.47,dualGuides:false});
const variants=copy(defaults);
for(const [index,name]of names.entries()){
  variants[name].ringSpeed=index*.2;
  variants[name].effects.shadowColor='#'+String(index+1).padStart(6,'0');
  variants[name].shadows.geometry=index%2===0;
  variants[name].geometryBySeries.fur=index%2?'orbit':'signature';
}
const encoded=encode(variants);
assert.equal(encoded.couture.length,51,'tuple-v1 has a fixed 51-slot schema');
assert.equal(encoded.couture[25],null,'missing optional dualSplit is explicit null');
assert.equal(encoded.couture[26],null,'missing optional dualGuides is explicit null');
assert.equal(encoded.dual[25],.47);
assert.equal(encoded.dual[26],false);
assert.deepEqual(decode(encoded,defaults),variants,'all thirteen full variants round-trip');
assert.deepEqual(decode(copy(encoded),{}),{},'unknown variants cannot enter a project');
assert.deepEqual(decode(null,defaults),defaults,'null storage starts from defaults');
assert.deepEqual(decode({},defaults),defaults,'absent variants start from defaults');
assert.deepEqual(decode({couture:[]},defaults),defaults,'missing tuple slots keep defaults');
assert.deepEqual(decode({couture:Array(51).fill(null)},defaults),defaults,'explicit null slots keep defaults');
const extra=copy(encoded);extra.couture.push('future slot',{__proto__:{polluted:true}});extra.unrecognized=encoded.couture;
assert.deepEqual(decode(extra,defaults),variants,'future slots and unknown variants are ignored');
const bad=copy(encoded);bad.couture[0]='not-a-font';bad.couture[7]='(()=>{globalThis.ran=true})()';bad.couture[8]={polluted:true};bad.couture[9]=['not a boolean'];
const badResult=decode(bad,defaults);
assert.equal(badResult.couture.typeface,'not-a-font','scalar validation belongs to restore');
assert.equal(badResult.couture.ringSpeed,'(()=>{globalThis.ran=true})()','input remains inert text');
assert.equal(scope.ran,undefined,'decoding never evaluates input');
assert.equal(badResult.couture.ringScale,defaults.couture.ringScale,'objects cannot replace scalar values');
assert.equal(badResult.couture.textMotion,defaults.couture.textMotion,'arrays cannot replace scalar values');
const malicious=JSON.parse('{"__proto__":["bad"],"constructor":["bad"],"couture":null}');
assert.deepEqual(decode(malicious,defaults),defaults);
assert.equal({}.polluted,undefined,'prototype pollution is rejected');
const withUnknown=copy(variants);withUnknown.couture.unknownSetting='discard';withUnknown.couture.effects.unknownEffect='discard';
assert.deepEqual(encode(withUnknown),encoded,'only the documented fixed paths are encoded');
const unchanged=copy(defaults),decoded=scope.decodeStudioVariants(encoded,defaults);
decoded.couture.effects.shadowColor='#ffffff';decoded.couture.geometryBySeries.fur='none';decoded.couture.shadows.title=false;
assert.deepEqual(defaults,unchanged,'decoding never mutates immutable defaults');
assert.equal(decoded.brutalist.effects.shadowColor,variants.brutalist.effects.shadowColor,'nested variant settings are independent');
encoded.couture[27]=false;
assert.equal(decoded.couture.effects.gradeEnabled,true,'decoded values do not retain input references');
const rawBytes=Buffer.byteLength(JSON.stringify(variants),'utf8'),tupleBytes=Buffer.byteLength(JSON.stringify(encode(variants)),'utf8');
assert.ok(tupleBytes<rawBytes*.55,'the thirteen-variant payload has ample room below the host limit');
console.log(`PASS: tuple-v1 preserves thirteen variants, defaults, optional fields, independent nested values and inert input; variants ${rawBytes} -> ${tupleBytes} bytes.`);
